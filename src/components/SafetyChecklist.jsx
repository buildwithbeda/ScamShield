import React, { useState } from 'react';
import { ShieldCheck, CheckCircle2, AlertOctagon, Share2, Copy, Check, MessageSquare, RotateCcw } from 'lucide-react';

export default function SafetyChecklist({
  analysis,
  onReset
}) {
  const [copiedWarning, setCopiedWarning] = useState(false);
  const [copiedReport, setCopiedReport] = useState(false);

  const { nextSteps, whatsappWarning, score, verdict, summary, scamCategories, analysisTimestamp } = analysis;

  const handleCopyWarning = async () => {
    if (!whatsappWarning) return;
    try {
      await navigator.clipboard.writeText(whatsappWarning);
      setCopiedWarning(true);
      setTimeout(() => setCopiedWarning(false), 2500);
    } catch {
      setCopiedWarning(false);
    }
  };

  const handleCopyReport = async () => {
    const reportText = `SCAMSHIELD THREAT ASSESSMENT REPORT
Date & Time: ${new Date(analysisTimestamp).toLocaleString()}
Analysis Method: Offline Deterministic Heuristic Engine

Verdict: ${verdict}
Risk Score: ${score}/100
Categories: ${scamCategories.join(', ') || 'None detected'}

Summary:
${summary}

Recommended Actions:
${nextSteps.map((step, idx) => `${idx + 1}. ${step.action}`).join('\n')}

Helpline: Dial 1930 for National Cyber Crime Reporting in India.
Portal: https://cybercrime.gov.in
Report generated by ScamShield (Independent Digital Safety Platform).`;

    try {
      await navigator.clipboard.writeText(reportText);
      setCopiedReport(true);
      setTimeout(() => setCopiedReport(false), 2500);
    } catch {
      setCopiedReport(false);
    }
  };

  if (!nextSteps || nextSteps.length === 0) return null;

  return (
    <div className="bg-white rounded-xl border border-[#DCE4EC] p-6 shadow-sm">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 mb-4 pb-2 border-b border-[#E2E8F0]">
        <div className="flex items-center gap-2">
          <ShieldCheck className="w-5 h-5 text-[#15803D]" />
          <h3 className="text-sm font-bold tracking-wide text-[#092B49] uppercase font-sans">
            Recommended Safety Actions
          </h3>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center flex-wrap gap-2">
          {/* Copy Report */}
          <button
            type="button"
            onClick={handleCopyReport}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-semibold bg-white hover:bg-slate-50 text-[#123B64] border border-[#CBD5E1] transition-all shadow-sm"
          >
            {copiedReport ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-600" />
                <span className="text-emerald-700 font-bold">Report Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy Report</span>
              </>
            )}
          </button>

          {/* Copy for WhatsApp */}
          {whatsappWarning && (
            <button
              type="button"
              onClick={handleCopyWarning}
              className={`flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-semibold transition-all shadow-sm ${
                copiedWarning
                  ? 'bg-emerald-600 text-white'
                  : 'bg-[#15803D] hover:bg-[#166534] text-white'
              }`}
            >
              {copiedWarning ? (
                <>
                  <Check className="w-3.5 h-3.5" />
                  <span>Warning Copied!</span>
                </>
              ) : (
                <>
                  <Share2 className="w-3.5 h-3.5" />
                  <span>Copy Warning for WhatsApp</span>
                </>
              )}
            </button>
          )}

          {/* Reset / Analyse Another */}
          {onReset && (
            <button
              type="button"
              onClick={onReset}
              className="flex items-center gap-1 px-3 py-1.5 rounded-md text-xs font-semibold text-[#52667A] hover:text-[#092B49] hover:bg-slate-100 border border-[#CBD5E1] transition-all"
            >
              <RotateCcw className="w-3.5 h-3.5" />
              <span>Analyse Another</span>
            </button>
          )}
        </div>
      </div>

      {/* Checklist items */}
      <div className="space-y-2.5">
        {nextSteps.map((step) => {
          let badgeColor = 'bg-[#F8FAFC] text-[#243447] border-[#E2E8F0]';
          let icon = <CheckCircle2 className="w-4 h-4 text-emerald-600 flex-shrink-0 mt-0.5" />;

          if (step.type === 'critical') {
            badgeColor = 'bg-red-50 text-red-950 border-red-200';
            icon = <AlertOctagon className="w-4 h-4 text-red-600 flex-shrink-0 mt-0.5" />;
          } else if (step.type === 'caution') {
            badgeColor = 'bg-amber-50 text-amber-950 border-amber-200';
            icon = <AlertOctagon className="w-4 h-4 text-amber-600 flex-shrink-0 mt-0.5" />;
          }

          return (
            <div
              key={step.id}
              className={`p-3 rounded-lg border flex items-start gap-3 transition-colors ${badgeColor}`}
            >
              {icon}
              <div className="text-xs sm:text-sm font-medium leading-relaxed">
                {step.action}
              </div>
            </div>
          );
        })}
      </div>

      {/* Cyber Helpline Notice for Indian Context */}
      <div className="mt-4 pt-3.5 border-t border-[#E2E8F0] flex flex-wrap items-center justify-between text-xs text-[#52667A] gap-2">
        <span className="flex items-center gap-1.5">
          <MessageSquare className="w-3.5 h-3.5 text-[#0B5CAD]" />
          <span>National Cyber Crime Helpline: <strong>1930</strong> (Free 24x7)</span>
        </span>
        <a
          href="https://cybercrime.gov.in"
          target="_blank"
          rel="noopener noreferrer"
          className="text-[#0B5CAD] hover:underline font-semibold font-mono"
        >
          cybercrime.gov.in
        </a>
      </div>
    </div>
  );
}
